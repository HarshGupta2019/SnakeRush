const PROCEDURAL_PREFIXES = ['Cosmic', 'Solar', 'Mystic', 'Golden', 'Crystal', 'Shadow', 'Neon', 'Astral', 'Emerald', 'Infernal', 'Lunar', 'Cyber', 'Radiant', 'Vortex', 'Imperial', 'Eternal', 'Grand', 'Titan'];
const PROCEDURAL_NOUNS = ['Trophy', 'Anchor', 'Spire', 'Crown', 'Wings', 'Emblem', 'Shield', 'Nexus', 'Artifact', 'Prism', 'Labyrinth', 'Beacon', 'Sigil', 'Castle', 'Dragon', 'Mandala'];

/**
 * Procedurally generates a rich, high-resolution silhouette for any level from 1 to 10000+
 */
export function getProceduralShapeTemplate(levelId: number): ShapeTemplate {
  // Directly map curated handcrafted templates
  const templateIdx = (levelId - 1) % SHAPE_TEMPLATES.length;
  const base = SHAPE_TEMPLATES[templateIdx];

  if (levelId <= SHAPE_TEMPLATES.length) {
    return {
      ...base,
      name: base.name,
    };
  }

  // Deterministic seed for procedurally crafted levels above template count
  const seed = (levelId * 9301 + 49297) % 233280;
  const rand = (offset: number) => {
    const s = (seed + offset * 1337) % 233280;
    return s / 233280;
  };

  const prefix = PROCEDURAL_PREFIXES[Math.floor(rand(1) * PROCEDURAL_PREFIXES.length)];
  const noun = PROCEDURAL_NOUNS[Math.floor(rand(2) * PROCEDURAL_NOUNS.length)];
  const icon = PROCEDURAL_ICONS[Math.floor(rand(3) * PROCEDURAL_ICONS.length)];
  const color = PROCEDURAL_COLORS[Math.floor(rand(4) * PROCEDURAL_COLORS.length)];

  // High-resolution grid dimensions
  const width = 15;
  const height = 15;

  const matrix: string[] = [];
  const halfW = Math.ceil(width / 2);

  for (let y = 0; y < height; y++) {
    let leftHalf = '';
    const distYFromCenter = Math.abs(y - Math.floor(height / 2));

    for (let x = 0; x < halfW; x++) {
      const distXFromCenter = Math.abs(x - Math.floor(width / 2));
      const dist = Math.sqrt(distXFromCenter * distXFromCenter + distYFromCenter * distYFromCenter);

      // Symmetric harmonic pattern
      const harmonic = Math.sin(dist * 1.2 + levelId * 0.3) + Math.cos(x * 0.7 + y * 0.7);
      const isFilled = harmonic > -0.15 || (distYFromCenter <= 2 && distXFromCenter <= 3) || (x === 0 && y % 2 === 0);

      leftHalf += isFilled ? '#' : '.';
    }

    // Mirror to right half for elegant symmetry
    let fullRow = leftHalf;
    for (let x = width - halfW - 1; x >= 0; x--) {
      fullRow += leftHalf[x];
    }
    matrix.push(fullRow.slice(0, width));
  }

  return {
    name: `${prefix} ${noun}`,
    icon,
    width,
    height,
    matrix,
    colorHint: color,
  };
}
